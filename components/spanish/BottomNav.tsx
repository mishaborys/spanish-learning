const NAV_ITEMS = [
  { href: "/",           label: "Теми",      Icon: BookIcon,       exact: true  },
  { href: "/review",     label: "Повторення", Icon: RepeatIcon,    exact: false },
  { href: "/homework",   label: "ДЗ",        Icon: HomeworkIcon,   exact: false },
  { href: "/dictionary", label: "Словник",   Icon: DictionaryIcon, exact: false },
];

export function BottomNav() {
  const pathname = usePathname();

  return (
    <nav className="fixed bottom-0 inset-x-0 z-40 border-t bg-background/95 backdrop-blur supports-[backdrop-filter]:bg-background/80">
      <div className="max-w-lg mx-auto flex">
        {NAV_ITEMS.map(({ href, label, Icon, exact }) => {
          const active = exact ? pathname === href : pathname.startsWith(href);
          return (
            <Link
              key={href}
              href={href}
              className={`flex-1 flex flex-col items-center justify-center gap-1 py-3 transition-colors relative ${
                active ? "text-primary" : "text-muted-foreground hover:text-foreground"
              }`}
            >
              {active && (
                <span className="absolute top-0 left-1/2 -translate-x-1/2 w-8 h-0.5 rounded-full bg-primary" />
              )}
              <Icon />
              <span className={`text-[11px] font-medium ${active ? "font-semibold" : ""}`}>{label}</span>
            </Link>
          );
        })}
      </div>
    </nav>
  );
}
